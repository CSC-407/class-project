import { useState } from 'react'
import { CalendarDays, Building2, Layers, AlertOctagon, Scale, FileDown, FileText, FileSpreadsheet, Download, History } from 'lucide-react'
import { api, useApi } from '../../lib/api'
import { useToast } from '../../context/ToastContext'
import { useAuth } from '../../context/AuthContext'
import { Card, CardHeader, PageHeader, Button, Modal, Input, SegmentedControl, Table, Th, Td, StatusChip, EmptyState, Badge } from '../../components/ui'
import { naira, formatDate, formatDateTime, downloadCSV, escapeHtml } from '../../lib/format'
import { useDocumentTitle } from '../../lib/hooks'

const REPORTS = [
  { id: 'daily', icon: CalendarDays, title: 'Daily collection', body: 'Confirmed payments per day with method breakdown.' },
  { id: 'faculty', icon: Building2, title: 'Collection per faculty', body: 'Expected vs collected, collection rate by faculty.' },
  { id: 'fee', icon: Layers, title: 'Collection per fee item', body: 'Totals for tuition, hostel, levies and other items.' },
  { id: 'debtors', icon: AlertOctagon, title: 'Debtors list', body: 'Every student with an outstanding balance.' },
  { id: 'recon', icon: Scale, title: 'Reconciliation', body: 'Gateway records matched against bank settlements.' },
]

function printReport(w, title, rows, meta) {
  if (!w) return false
  const headers = Object.keys(rows[0] || {})
  // Every value is HTML-escaped before it goes into the document.
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${escapeHtml(title)}</title>
  <style>body{font-family:system-ui,sans-serif;margin:32px;color:#0f1b2d}h1{font-size:20px;margin:0}p{color:#55637a;font-size:12px}
  table{width:100%;border-collapse:collapse;font-size:12px;margin-top:16px}th,td{border-bottom:1px solid #dfe5ee;padding:6px 8px;text-align:left}th{background:#eef2f7}td.n{text-align:right;font-variant-numeric:tabular-nums}</style></head>
  <body><h1>Kingsgate University: ${escapeHtml(title)}</h1><p>${escapeHtml(meta)}</p><table><thead><tr>${headers.map((h) => `<th>${escapeHtml(h)}</th>`).join('')}</tr></thead>
  <tbody>${rows.map((r) => `<tr>${headers.map((h) => `<td class="${typeof r[h] === 'number' ? 'n' : ''}">${escapeHtml(typeof r[h] === 'number' && h !== 'Transactions' && h !== 'Payments' && h !== 'Rate %' ? naira(r[h]) : String(r[h]))}</td>`).join('')}</tr>`).join('')}</tbody></table>
  <script>window.onload=()=>window.print()</script></body></html>`)
  w.document.close()
  return true
}

export default function Reports() {
  useDocumentTitle('Reports')
  const { user } = useAuth()
  const toast = useToast()
  const [active, setActive] = useState(null)
  const [from, setFrom] = useState(new Date(Date.now() - 30 * 86400000).toISOString().slice(0, 10))
  const [to, setTo] = useState(new Date().toISOString().slice(0, 10))
  const [format, setFormat] = useState('csv')
  const [loading, setLoading] = useState(false)
  const historyRes = useApi('/api/admin/reports/history', { pick: (r) => r.history })
  const history = historyRes.data || []

  const generate = async (again) => {
    const r = again ? REPORTS.find((x) => x.title === again.report) : active
    const fmt = again ? again.format : format
    // Open the print window during the click, so pop-up blockers allow it.
    const w = fmt === 'pdf' ? window.open('', '_blank') : null
    setLoading(true)
    try {
      const res = await api(`/api/admin/reports/${r.id}`, { method: 'POST', body: { from, to, format: fmt } })
      if (!res.rows.length) {
        w?.close()
        toast('No data in this date range. Try a wider range.', { type: 'warning' })
        return
      }
      if (fmt === 'pdf') {
        if (!w) toast('Allow pop-ups to view the PDF', { type: 'warning' })
        else printReport(w, r.title, res.rows, `${formatDate(from)} to ${formatDate(to)} · Generated by ${user.name} on ${formatDateTime(new Date())}`)
      } else downloadCSV(`${r.id}-report-${to}.csv`, res.rows)
      toast(`${r.title} generated (${res.rows.length} rows)`)
      historyRes.reload({ silent: true })
      setActive(null)
    } catch (e) {
      w?.close()
      toast(e.message, { type: 'error' })
    } finally {
      setLoading(false)
    }
  }

  const fmtIcon = { pdf: FileText, csv: FileDown, excel: FileSpreadsheet }

  return (
    <>
      <PageHeader title="Reports & Exports" description="Generate financial reports for the Bursary, management and auditors." breadcrumbs={[{ label: 'Reports' }]} />
      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-3">
        {REPORTS.map((r) => (
          <Card key={r.id} className="flex flex-col p-5">
            <span className="flex size-11 items-center justify-center rounded-xl bg-brand-50 text-brand-700 dark:bg-brand-500/15 dark:text-brand-200"><r.icon className="size-5" aria-hidden /></span>
            <h2 className="mt-4 font-semibold">{r.title}</h2>
            <p className="mt-1 flex-1 text-sm text-muted">{r.body}</p>
            <div className="mt-4 flex items-center gap-2">
              <Button variant="secondary" size="sm" onClick={() => setActive(r)} icon={Download}>Generate</Button>
              <span className="text-xs text-muted">PDF · CSV · Excel</span>
            </div>
          </Card>
        ))}
      </div>

      <Card className="mt-8">
        <CardHeader title="Generated reports" description="The last 20 reports, kept for audit" icon={History} />
        {history.length === 0 ? (
          <EmptyState icon={FileText} title="No reports yet">Reports you generate will be listed here.</EmptyState>
        ) : (
          <Table className="mt-3">
            <thead><tr><Th>Report</Th><Th className="hidden md:table-cell">Range</Th><Th>Format</Th><Th className="hidden sm:table-cell">Generated</Th><Th>Status</Th><Th align="right"><span className="sr-only">Action</span></Th></tr></thead>
            <tbody>
              {history.map((h) => {
                const Icon = fmtIcon[h.format]
                return (
                  <tr key={h.id} className="hover:bg-subtle/60">
                    <Td><p className="font-medium">{h.report}</p><p className="text-xs text-muted">{h.rows} rows · by {h.by}</p></Td>
                    <Td className="hidden md:table-cell text-muted">{h.range}</Td>
                    <Td><Badge tone="neutral" icon={Icon}>{h.format.toUpperCase()}</Badge></Td>
                    <Td className="hidden sm:table-cell whitespace-nowrap text-muted">{formatDateTime(h.at)}</Td>
                    <Td><StatusChip status={h.status} label="Ready" /></Td>
                    <Td align="right"><Button size="icon-sm" variant="ghost" aria-label={`Download ${h.report} again`} onClick={() => generate(h)}><Download className="size-4" /></Button></Td>
                  </tr>
                )
              })}
            </tbody>
          </Table>
        )}
      </Card>

      <Modal
        open={!!active}
        onClose={() => setActive(null)}
        title={active?.title}
        description={active?.body}
        footer={
          <>
            <Button variant="secondary" onClick={() => setActive(null)}>Cancel</Button>
            <Button loading={loading} icon={Download} onClick={() => generate()}>Generate report</Button>
          </>
        }
      >
        <div className="space-y-5">
          <div className="grid gap-4 sm:grid-cols-2">
            <Input label="From" type="date" value={from} max={to} onChange={(e) => setFrom(e.target.value)} />
            <Input label="To" type="date" value={to} min={from} onChange={(e) => setTo(e.target.value)} />
          </div>
          <div>
            <p className="mb-2 text-sm font-medium">Format</p>
            <SegmentedControl label="Format" value={format} onChange={setFormat} options={[{ value: 'pdf', label: 'PDF', icon: FileText }, { value: 'csv', label: 'CSV', icon: FileDown }, { value: 'excel', label: 'Excel', icon: FileSpreadsheet }]} />
            {format === 'excel' && <p className="mt-2 text-xs text-muted">Excel exports download as a UTF-8 CSV that opens directly in Excel.</p>}
          </div>
          <p className="text-xs text-muted">CSV exports escape values that begin with =, +, - or @ to prevent spreadsheet formula injection.</p>
        </div>
      </Modal>
    </>
  )
}
